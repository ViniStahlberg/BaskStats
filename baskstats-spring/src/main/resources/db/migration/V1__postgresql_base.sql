-- PostgreSQL equivalent of the MySQL model supplied in capturas/.
-- Existing scraper tables are preserved. No production data is seeded.
CREATE TABLE IF NOT EXISTS temporada (
 id_temporada integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nome varchar(100),ano_inicio smallint,ano_fim smallint);
CREATE TABLE IF NOT EXISTS time (
 id_time integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,nome varchar(150) NOT NULL,sigla varchar(10));
CREATE TABLE IF NOT EXISTS jogadora (
 id_jogadora integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,nome varchar(150) NOT NULL,
 peso numeric(5,2),altura numeric(4,2),envergadura numeric(4,2),data_ultima_medicao date);
CREATE TABLE IF NOT EXISTS partida (
 id_partida integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,temporada_id integer REFERENCES temporada,
 confronto varchar(255),data_hora timestamp,local varchar(150),arbitros varchar(255),link_video varchar(500));
CREATE TABLE IF NOT EXISTS partida_time (
 id_partida_time integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,partida_id integer NOT NULL REFERENCES partida,
 time_id integer NOT NULL REFERENCES time,tecnico varchar(150),placar_final smallint,
 UNIQUE(partida_id,time_id));
CREATE TABLE IF NOT EXISTS elenco (
 id_elenco integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,jogadora_id integer NOT NULL REFERENCES jogadora,
 time_id integer NOT NULL REFERENCES time,temporada_id integer NOT NULL REFERENCES temporada,numero_camisa smallint);
CREATE TABLE IF NOT EXISTS quarto (
 id_quarto integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,partida_id integer NOT NULL REFERENCES partida,
 numero smallint,video_inicio_segundos numeric(8,1),video_fim_segundos numeric(8,1));
CREATE TABLE IF NOT EXISTS placarquarto (
 id_placar_quarto integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,quarto_id integer REFERENCES quarto,
 partida_time_id integer REFERENCES partida_time,placar_acumulado smallint);
CREATE TABLE IF NOT EXISTS estatisticajogadorapartida (
 id_estatistica_jogadora integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 partida_time_id integer NOT NULL REFERENCES partida_time,jogadora_id integer NOT NULL REFERENCES jogadora,
 numero_camisa smallint,tempo_jogado varchar(10),pontos_feitos smallint,pontos_tentados smallint,
 arremesso_3_feitos smallint,arremesso_3_tentados smallint,arremesso_2_feitos smallint,arremesso_2_tentados smallint,
 lance_livre_feitos smallint,lance_livre_tentados smallint,rebote_ofensivo smallint,rebote_defensivo smallint,
 rebote_total smallint,assistencias smallint,roubos_bola smallint,turnovers smallint,en smallint,
 faltas_cometidas smallint,faltas_recebidas smallint,er smallint,vi smallint,mais_menos smallint,eficiencia smallint);
CREATE TABLE IF NOT EXISTS estatisticatimepartida (
 id_estatistica_time integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,partida_time_id integer REFERENCES partida_time,
 tipo varchar(30),pontos_feitos smallint,pontos_tentados smallint,arremesso_3_feitos smallint,arremesso_3_tentados smallint,
 arremesso_2_feitos smallint,arremesso_2_tentados smallint,lance_livre_feitos smallint,lance_livre_tentados smallint,
 rebote_ofensivo smallint,rebote_defensivo smallint,rebote_total smallint,assistencias smallint,roubos_bola smallint,
 turnovers smallint,faltas_cometidas smallint,faltas_recebidas smallint);
CREATE TABLE IF NOT EXISTS extraspartidatime (
 id_extras integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,partida_time_id integer REFERENCES partida_time,
 reservas_pontos integer,pontos_garrafao smallint,desqualificados varchar(255));
CREATE TABLE IF NOT EXISTS medidafisica (
 id_medida integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,jogadora_id integer REFERENCES jogadora,
 data_medicao date,peso numeric(5,2),altura numeric(4,2),envergadura numeric(4,2));
CREATE TABLE IF NOT EXISTS tipoevento (
 id_tipo_evento integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,nome varchar(50),descricao varchar(255));
CREATE TABLE IF NOT EXISTS lance (
 id_lance integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,quarto_id integer REFERENCES quarto,
 partida_time_id integer REFERENCES partida_time,jogadora_id integer REFERENCES jogadora,tipo_evento_id integer REFERENCES tipoevento,
 clock varchar(5),segundos_decorridos_quarto smallint,timestamp_video_segundos numeric(8,1),ordem_no_quarto smallint,
 descricao_original varchar(500),jogador_feitos smallint,jogador_tentados smallint,equipe_feitos smallint,equipe_tentados smallint);
CREATE TABLE IF NOT EXISTS categoriaclipe (
 id_categoria_clipe integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,nome varchar(50),descricao varchar(255));
CREATE TABLE IF NOT EXISTS clipe (
 id_clipe integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,categoria_clipe_id integer REFERENCES categoriaclipe,
 partida_id integer REFERENCES partida,inicio_segundos numeric(8,1),fim_segundos numeric(8,1),
 duracao_segundos numeric(8,1),caminho_arquivo varchar(500));
CREATE TABLE IF NOT EXISTS clipe_lance (clipe_id integer REFERENCES clipe,lance_id integer REFERENCES lance,PRIMARY KEY(clipe_id,lance_id));
