-- Position is not present in the original model: store it explicitly, never infer from shirt number.
ALTER TABLE elenco ADD COLUMN IF NOT EXISTS posicao varchar(40);
CREATE TABLE usuario (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,email varchar(254) NOT NULL UNIQUE,
 senha_hash varchar(100) NOT NULL,criado_em timestamptz NOT NULL DEFAULT now());
CREATE TABLE playlist (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,nome varchar(150) NOT NULL CHECK(length(trim(nome))>0),
 usuario_email varchar(254) NOT NULL REFERENCES usuario(email),criado_em timestamptz NOT NULL DEFAULT now());
CREATE TABLE playlist_clipe (
 playlist_id integer NOT NULL REFERENCES playlist(id) ON DELETE CASCADE,
 clipe_id integer NOT NULL REFERENCES clipe(id_clipe) ON DELETE CASCADE,ordem integer NOT NULL DEFAULT 0,
 PRIMARY KEY(playlist_id,clipe_id));
CREATE TABLE treino (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,titulo varchar(150) NOT NULL CHECK(length(trim(titulo))>0),
 descricao text NOT NULL DEFAULT '',jogadora_id integer REFERENCES jogadora(id_jogadora),data date,
 usuario_email varchar(254) NOT NULL REFERENCES usuario(email),criado_em timestamptz NOT NULL DEFAULT now());
CREATE INDEX IF NOT EXISTS ix_stats_partida_jogadora ON estatisticajogadorapartida(partida_time_id,jogadora_id);
CREATE INDEX IF NOT EXISTS ix_elenco_time_temporada ON elenco(time_id,temporada_id,jogadora_id);
CREATE INDEX IF NOT EXISTS ix_partida_data ON partida(data_hora);
CREATE INDEX IF NOT EXISTS ix_partida_time_time ON partida_time(time_id,partida_id);
CREATE INDEX ix_playlist_owner ON playlist(usuario_email);
CREATE INDEX ix_treino_owner ON treino(usuario_email);
